IMG_W = 520   # PAL active pixels per line
IMG_H = 576   # PAL active lines (interlaced: 288 F1 + 288 F2)

def clear_frame():
    """Return a 299 520-element bytearray of zeros (all black)."""
    return bytearray(IMG_W * IMG_H)

def draw_text(pixels, text, x=0, y=0):
    """
    Render ASCII text into the pixel array at screen position (x, y).
    Each character is 8 pixels wide × 8 pixels tall.
    Pixels outside the 520×576 frame are silently clipped.
    """
    for ci, ch in enumerate(text):
        asc = ord(ch) - 32
        if not (0 <= asc <= 94):
            asc = 0              # unknown → space (blank)
        glyph = FONT[asc]
        for row in range(8):
            fb = glyph[row]
            for bit in range(8):
                if fb & (0x80 >> bit):   # bit 7 = left pixel
                    px = x + ci * 8 + bit
                    py = y + row
                    if 0 <= px < IMG_W and 0 <= py < IMG_H:
                        pixels[py * IMG_W + px] = 1

def save_bin(pixels, path="pal_frame.bin"):
    """Write pixel array as raw binary (one byte per pixel)."""
    with open(path, "wb") as f:
        f.write(bytes(pixels))
    whites = sum(1 for b in pixels if b)
    print(f"Saved {len(pixels)} bytes → {path}  ({whites} white pixels)")

# ---------------------------------------------------------------------------
# Main: render centred text lines and save
# ---------------------------------------------------------------------------
def main():
    lines = sys.argv[1:] if len(sys.argv) > 1 else [
        "PAL 625/50 INTERLACED",
        "FPGA VIDEO IP CORE",
        "BRAM TEXT OVERLAY",
    ]

    pixels = clear_frame()

    line_h = 12          # 8 px font + 4 px gap between lines
    total_h = len(lines) * line_h - 4          # total block height
    start_y = (IMG_H - total_h) // 2          # vertically centred

    for i, line in enumerate(lines):
        x = (IMG_W - len(line) * 8) // 2      # horizontally centred
        y = start_y + i * line_h
        draw_text(pixels, line, x, y)
        print(f"  Line {i}: \"{line}\"  at pixel ({x}, {y})")

    save_bin(pixels)

if __name__ == "__main__":
    main()
