"""
pal_text_bram.py
================
Generates a 520x576 1-bit PAL pixel array with rendered 8x8 text and
saves it as a raw binary file (one byte per pixel: 0=black, 1=white).

LabVIEW reads the binary file and writes every byte to the BRAM write
port using the natural-sequential address layout expected by pal_tv_bram_top
(sel = 4):

    byte index i  →  bram_wr_addr = i  (U32, 0..299519)
                     bram_wr_data = pixel[i]  (Boolean / U8, 0 or 1)

Usage:
    python pal_text_bram.py                 # default 3-line demo
    python pal_text_bram.py "HELLO WORLD"   # single custom line

Output: pal_frame.bin  (299 520 bytes)

LabVIEW wiring after reading the file:
  1. Read Binary File → U8 1D array (299 520 elements)
  2. For Loop  i = 0 .. 299519
        bram_wr_addr ← i   (cast to U32)
        bram_wr_data ← array[i] != 0   (Boolean)
        bram_wr_en   ← TRUE  (pulse one FPGA clock)
  3. Set sel = 4, release rst → live PAL display
"""

